/**
 * AI-1, AI-10: the guide files in the Claude folder. CLAUDE.md is what Claude Code reads first in
 * the folder; guide/data-model.md describes every record type, field and dependency. Both are built
 * from the schema (schema.ts) and the warning rules, so they always match the app.
 */
import type { World } from '../model';
import { RULES } from '../warnings';
import { BASE_FIELDS, CLAUDE_COLLECTIONS, DATE_RULES, DEPENDENCY_RULES, Field, READ_ONLY_COLLECTIONS, SCHEMA } from './schema';

/** The connector's name in Claude Code (.mcp.json); its tools are called mcp__story-world__<tool>. */
export const MCP_SERVER_NAME = 'story-world';

function typeText(f: Field): string {
  switch (f.t) {
    case 'string': return 'text';
    case 'number': return `number${f.int ? ' (whole)' : ''}${f.min !== undefined || f.max !== undefined ? ` ${f.min ?? '…'}–${f.max ?? '…'}` : ''}`;
    case 'boolean': return 'true/false';
    case 'enum': return f.values.map((v) => `"${v}"`).join(' | ');
    case 'strings': return 'list of text';
    case 'date': return 'date';
    case 'latlng': return '{lat, lng}';
    case 'latlngs': return 'list of {lat, lng}';
    case 'ref': return `id of ${f.to.join('/')}`;
    case 'refs': return `ids of ${f.to.join('/')}`;
    case 'subject': return '{kind: "character"|"group", id}';
    case 'list': return 'list of entries';
    case 'geo': return 'GeoJSON MultiPolygon coordinates';
    case 'app': return 'set by the app';
  }
}

function fieldRows(fields: Record<string, Field>, indent = ''): string[] {
  const out: string[] = [];
  for (const [k, f] of Object.entries(fields)) {
    if (k === 'id' && f.t === 'app' && indent) continue;
    const req = 'req' in f && f.req ? ' **required**' : '';
    out.push(`${indent}- \`${k}\` (${typeText(f)})${req}: ${f.desc}`);
    if (f.t === 'list') out.push(...fieldRows(f.fields, indent + '  '));
  }
  return out;
}

/** AI-10: the whole data model, for guide/data-model.md and the data_model tool. */
export function dataModelGuide(only?: string): string {
  const parts: string[] = [];
  if (!only) {
    parts.push('# Data model', '', 'Generated by Story World Tracker from its own code. Every record Claude can propose to change is listed with its fields. Field names are exactly as in proposals.', '');
    parts.push('## Fields every record has', '', ...fieldRows(BASE_FIELDS), '');
    parts.push('## Dates', '', ...DATE_RULES.map((r) => `- ${r}`), '');
    parts.push('## How records depend on each other', '', ...DEPENDENCY_RULES.map((r) => `- ${r}`), '');
  }
  for (const c of CLAUDE_COLLECTIONS) {
    if (only && only !== c) continue;
    const s = SCHEMA[c];
    parts.push(`## ${c}`, '', s.about, '', ...fieldRows(s.fields));
    const defs = Object.entries(s.defaults);
    if (defs.length) parts.push('', `Defaults for a new record: ${defs.map(([k, v]) => `\`${k}\` = ${JSON.stringify(v)}`).join(', ')}.`);
    parts.push('');
  }
  if (!only) {
    parts.push('## Read only', '', `Claude can read but not change: ${READ_ONLY_COLLECTIONS.join(', ')}. Scene text changes with the "text" change; the painted map with the "terrain" change.`, '');
    parts.push('## Warnings the app checks', '', 'Every proposal is checked against these before Ojon sees it; new warnings are shown with the proposal.', '', ...Object.entries(RULES).map(([id, r]) => `- \`${id}\` (${r.requirement}, ${r.severity}): ${r.name}`), '');
  }
  if (only && !(CLAUDE_COLLECTIONS as readonly string[]).includes(only)) return `"${only}" is not a collection Claude can change. Collections: ${CLAUDE_COLLECTIONS.join(', ')}.`;
  return parts.join('\n');
}

export const CHANGE_FORMAT = `Each change is one of:

- \`{ "op": "create", "collection": "<collection>", "record": { "id": "new:<name>", …fields } }\`. The "new:" id lets other changes in the same proposal point at it.
- \`{ "op": "update", "collection": "<collection>", "id": "<id>", "set": { "<field>": <value>, … } }\`. Only the named fields change; \`null\` removes an optional field. Lists (aliases, attributes, knowers, versions…) are replaced whole, so send the full list.
- \`{ "op": "delete", "collection": "<collection>", "id": "<id>" }\`, with \`"cascade": true\` to also delete what cannot live without it, or \`"reassignTo": "<other id>"\` to move its links first.
- \`{ "op": "text", "sceneId": "<scene id>", "find": "<exact passage>", "replace": "<new words>" }\` replaces one passage of a scene (it must occur exactly once, inside one paragraph; a blank line in replace starts a new paragraph). Without "find" the whole scene text is replaced (Markdown: *italics*, **bold**, "* * *" for a break). Prefer passages: they keep comments and links.
- \`{ "op": "terrain", "shape": "area" | "line", "points": [{lat, lng}, …], "widthKm": 30, "land": "land" | "water", "heightM": 1200, "terrainType": "Forest" }\` paints the map inside an area or along a line (widthKm for lines). Give at least one of land, heightM, terrainType.
- \`{ "op": "border", "regionId": "<region id>", "area": [{lat, lng}, …], "mode": "add" | "remove", "from": "3/5/1044", "until": "…", "neighbours": "take" | "stop", "note": "Conquered by …" }\` changes a realm's land from a date (a conquest takes it from the neighbours; "stop" stops at their border).`;

/** AI-1: CLAUDE.md, the first file Claude Code reads in the Claude folder. */
export function claudeMd(world: World, opts: { directEdit: boolean }): string {
  const s = world.settings;
  const modes = s.travelModes.map((m) => `${m.name} (\`${m.id}\`, ${m.speedKmPerDay} km/day)`).join(', ');
  return `# ${s.name}: story world for Claude

This folder is a live, read-only copy of the story world "${s.name}" kept by Story World Tracker, the writer's app. The writer is Ojon. The app rewrites these files every time the world is saved, so **never edit files here**: changes would be lost and the app would not know about them.

## What is here

- \`world.md\`: the world at a glance (settings, counts, books, the current moment).
- \`manuscript/\`: the text of every scene, book by book and chapter by chapter, with the scene's date, point of view, place and cast at the top. Scene text lives in the app; Word is only for import and export.
- \`characters/\`, \`places/\`, \`groups/\`, \`events/\`, \`realms/\`: one page per record, with its id, fields, relationships, whereabouts and where it appears.
- \`timeline.md\`: everything that happens, in in-world date order.
- \`story/\`: plot threads, secrets and who knows them, scenarios (what-ifs), to-dos and plot holes, the margin comments on the text (\`story/comments.md\`), setups and payoffs, each book's structure (beats), the character arcs, the revision passes with the style checks in use (\`story/revision.md\`), the lines of dialogue tagged by character (\`story/dialogue.md\`) and where each book was sent (\`story/submissions.md\`).
- \`notes/\`: the writer's notebook, one file per note, in the notebook's folders (\`notes/Inbox/\` holds quick captures not sorted yet). Each note lists the records it is about.
- \`research/\`: the research files (images and PDFs) with what they are attached to (\`research/files.md\`), and copies of the files in \`research/files/\` that you can open and read.
- \`map.md\`: rivers, roads, lakes, mountain ranges and other map features; the painted terrain is summarised.
- \`warnings.md\`: what the app's checks currently flag.
- \`guide/data-model.md\`: **read this before proposing changes**. Every record type, every field, and how records depend on each other.
- \`data/world.json\`: the whole world as JSON (without the painted map and pictures), for exact lookups.

Every page starts with the record's \`id\`. Use ids in proposals and tool calls.

## Live tools

The app's connector (\`${MCP_SERVER_NAME}\`) answers precise questions while the world is open in the app: \`search\`, \`get_record\`, \`list_records\`, \`where_is\` (everyone or one character on a date), \`character_timeline\`, \`scene\` (text and context), \`warnings\`, \`reader_knows\` (what the reader knows by a chapter), \`travel_time\`, \`realm_at\`, \`data_model\`, \`check_changes\`, \`propose_changes\` and \`suggestions\`. Prefer the tools over the files when a question depends on dates (whereabouts, realms, what the reader knows): they use the app's own rules.

## Rules of this world

${DATE_RULES.map((r) => `- ${r}`).join('\n')}
- Places nest physically (room → castle → city). Kingdoms, empires, cultures and religions are **regions on layers**, not places; which realm a place belongs to follows from the political layer on a date, and borders change over time.
- A group's stays and journeys move all its members; a member's own entries win.
- Travel modes: ${modes}. Journeys without an arrival date get one from distance and speed.
- "Known" means known to the reader. The reader's view (\`reader_knows\`) shows the world as the reader knows it at the end of a chapter.
- What-if scenarios (\`story/scenarios.md\`) change records only inside the scenario; canon is untouched until the writer keeps it.

## Changing things

${opts.directEdit
    ? 'Ojon has switched on **direct editing** for this world: `propose_changes` applies a change at once (after the same checks). Every change is labelled as yours, listed in the Claude activity log and can be undone. Still, only change what Ojon asked for.'
    : 'You never change the world directly. Use `propose_changes`: each proposal arrives in the app\'s **Suggestions** list with a before/after preview (map changes as a ghost on the map). Ojon accepts or rejects it, change by change if they like.'}

1. Read \`guide/data-model.md\` (or call \`data_model\`) for the fields and dependencies of what you change.
2. Look up current values with \`get_record\` first; an update replaces whole fields.
3. Call \`check_changes\` to try a proposal without sending it. It refuses anything that would break a link or leave an orphan and tells you why, and it lists any new warnings (impossible travel, a river flowing uphill…).
4. Send it with \`propose_changes\`, with a short title and your reason. Big ideas ("an invasion in 1044", "a new kingdom in the south") can go as a what-if scenario: add \`"asScenario": { "name": …, "description": … }\`.
5. \`suggestions\` tells you what was accepted or rejected (with Ojon's note).

${CHANGE_FORMAT}

## Writing help

Ojon writes the novels; you help. When asked about the text, quote it from \`manuscript/\` or the \`scene\` tool. When suggesting prose, keep to their voice and tense and propose passages with the "text" change rather than rewriting whole scenes, unless asked. Words you write do not count towards their daily word goal.
`;
}

/** AI-5: the files that set Claude Code up in the folder. */
export function mcpJson(port: number, token: string): string {
  return JSON.stringify({ mcpServers: { [MCP_SERVER_NAME]: { type: 'http', url: `http://127.0.0.1:${port}/mcp`, headers: { Authorization: `Bearer ${token}` } } } }, null, 2) + '\n';
}

/** Claude Code settings for the folder: the connector is trusted; files here are read, never written. */
export function claudeSettingsJson(): string {
  return JSON.stringify({
    enabledMcpjsonServers: [MCP_SERVER_NAME],
    permissions: {
      allow: [`mcp__${MCP_SERVER_NAME}`, 'Read', 'Glob', 'Grep'],
      deny: ['Edit', 'Write', 'NotebookEdit', 'Bash'],
    },
  }, null, 2) + '\n';
}
